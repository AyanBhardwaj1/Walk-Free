/** Even-odd test of one point against one ring, on the flat lon/lat plane. */
function inRing(lon: number, lat: number, ring: readonly LonLat[]) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi
    )
      inside = !inside;
  }
  return inside;
}

/** Whether a point falls on (our rough idea of) land. */
export function isLand(lon: number, lat: number) {
  return LAND.some((ring) => inRing(lon, lat, ring));
}

/**
 * Evenly spaced points on land, `step` degrees apart. Each row of latitude
 * gets fewer points towards the poles so the dots keep the same spacing on
 * the sphere instead of bunching up.
 */
export function landDots(step = 2): LonLat[] {
  const dots: LonLat[] = [];
  for (let lat = -88 + step / 2; lat < 88; lat += step) {
    const perRow = Math.max(
      1,
      Math.round((360 / step) * Math.cos((lat * Math.PI) / 180)),
    );
    for (let i = 0; i < perRow; i++) {
      const lon = -180 + (i + 0.5) * (360 / perRow);
      if (isLand(lon, lat)) dots.push([lon, lat]);
    }
  }
  return dots;
}

/**
 * A point on a sphere of the given radius, in three.js axes: +Y is north
 * and longitude 0 faces +Z, so east is towards +X.
 */
export function lonLatToXYZ(
  lon: number,
  lat: number,
  radius = 1,
): [number, number, number] {
  const phi = (lat * Math.PI) / 180;
  const lambda = (lon * Math.PI) / 180;
  return [
    radius * Math.cos(phi) * Math.sin(lambda),
    radius * Math.sin(phi),
    radius * Math.cos(phi) * Math.cos(lambda),
  ];
}
