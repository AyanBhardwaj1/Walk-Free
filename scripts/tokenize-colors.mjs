// Turns every hex colour in src/style.css into a theme token named for the
// colour and the role it plays (background, text, line or shadow), with the
// editorial value as fallback, and lists them in src/theme-colors.ts.
// Re-runnable: existing tokens are re-classified. Run:
//   node scripts/tokenize-colors.mjs
import { readFileSync, writeFileSync } from "node:fs";

const file = "src/style.css";
const css = readFileSync(file, "utf8");
const HEX = /#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9a-zA-Z])/;
const expand = (hex) =>
  hex.length === 4 ? "#" + [...hex.slice(1)].map((c) => c + c).join("") : hex;

/** The role a colour plays in a declaration, from its property. */
function role(property) {
  if (/^(color|fill|caret-color|accent-color|text-decoration-color)$/.test(property)) return "fg";
  if (/^(border|outline|stroke|column-rule)/.test(property)) return "line";
  if (/shadow/.test(property)) return "shadow";
  return "bg";
}

const tokens = new Set();
const out = css.replace(
  /(^|[;{\s])(--[\w-]+|[a-z-]+)\s*:([^;{}]*)/g,
  (whole, lead, property, value) => {
    if (property.startsWith("--")) return whole;
    const r = role(property);
    const next = value
      // Existing tokens: var(--c-…, #hex) → re-classified.
      .replace(/var\(--c-[\w-]+,\s*(#[0-9a-fA-F]{3,8})\)/g, (_m, hex) => {
        const full = expand(hex.toLowerCase());
        tokens.add(`${r}-${full.slice(1)}`);
        return `var(--c-${r}-${full.slice(1)}, ${full})`;
      })
      // Bare hex colours.
      .replace(new RegExp(`(?<![\\w-]|, )${HEX.source}`, "g"), (match) => {
        const full = expand(match.toLowerCase());
        tokens.add(`${r}-${full.slice(1)}`);
        return `var(--c-${r}-${full.slice(1)}, ${full})`;
      });
    return `${lead}${property}:${next}`;
  },
);
writeFileSync(file, out);
writeFileSync(
  "src/theme-colors.ts",
  `// Generated by scripts/tokenize-colors.mjs: every colour in style.css,\n// as role-hex ("bg-fffdf6", "fg-313b30", "line-dcded3", "shadow-…").\nexport const THEME_COLORS = ${JSON.stringify([...tokens].sort(), null, 2)};\n`,
);
console.log(`${tokens.size} role tokens`);
