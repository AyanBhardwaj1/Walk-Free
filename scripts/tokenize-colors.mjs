// One-off: turns every hex colour in src/style.css into a theme token with
// its current value as the fallback (so the default look is unchanged), and
// lists the colours in src/theme-colors.ts for the theme engine.
// Run: node scripts/tokenize-colors.mjs
import { readFileSync, writeFileSync } from "node:fs";

const file = "src/style.css";
const css = readFileSync(file, "utf8");
const seen = new Set();
const expand = (hex) =>
  hex.length === 4 ? "#" + [...hex.slice(1)].map((c) => c + c).join("") : hex;
const out = css.replace(
  /(?<![\w-])#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9a-zA-Z])/g,
  (match, _hex, offset) => {
    // Leave tokens already written, and ids/selectors (never in this file).
    if (css.slice(Math.max(0, offset - 6), offset).includes("--c-"))
      return match;
    const full = expand(match.toLowerCase());
    seen.add(full);
    return `var(--c-${full.slice(1)}, ${full})`;
  },
);
writeFileSync(file, out);
writeFileSync(
  "src/theme-colors.ts",
  `// Generated by scripts/tokenize-colors.mjs: every colour in style.css.\nexport const THEME_COLORS = ${JSON.stringify([...seen].sort(), null, 2)};\n`,
);
console.log(`${seen.size} colours tokenized`);
